def get(table, key, fallback=None):
    """실측값을 꺼내고 신뢰도를 함께 돌려준다.

    layout.py 가 이걸로 값을 읽으면 빌드 로그에 measured/derived 가 남는다.
    """
    if key in table:
        v, src, conf = table[key]
        return v, conf
    return fallback, 'fallback'


def report(table, name):
    """신뢰도별 집계 — 어디를 더 파야 하는지 보인다."""
    from collections import Counter
    c = Counter(conf for _, _, conf in table.values())
    return "%s: %s" % (name, dict(c))
