def bracket_top(floor, col_h, kind='ikgong', tiers=1):
    """공포 상단 높이. 처마(eave)는 이 값 바로 위여야 한다.

    다포계: build_beams 가 평방을 +0.26 올리고, build_brackets 가
            z_base+0.30 부터 tiers*0.34 씩 쌓는다.
    익공계: 평방이 없고, build_ikgong 이 z_base+0.22 부터 tiers*0.30.
    """
    col_top = floor + col_h
    if kind == 'dapo':
        return col_top + 0.26 + 0.30 + tiers * 0.34 + 0.11
    return col_top + 0.02 + 0.22 + tiers * 0.30 + 0.16
