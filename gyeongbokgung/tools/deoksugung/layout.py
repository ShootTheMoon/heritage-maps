# -*- coding: utf-8 -*-
"""덕수궁 배치 — 궁 축 좌표계와 사이트 행렬.

**덕수궁 주축은 정북이 아니다.** OSM 건물 중심점 실측 결과
중화문 → 중화전이 방위각 **11.7°** (북에서 동으로). 준명당→즉조당이
103.5° 로 이 축과 거의 정확히 직교하는 것으로 교차검증했다.

좌표 규약
    U = 정면 방향 (+ 가 궁 동쪽)
    V = 주축 방향 (+ 가 안쪽/북쪽)
    원점 = 중화전 중심

모든 건물은 **원점에서 정면이 −Y 를 보도록** 만들고(경복궁과 같은 저작 규약),
배치는 site_matrix 로 한 번에 씌운다.
"""

import math

# 사이트 전체 Z 회전.
# 유도: R_z(θ)·(0,1,0) = (−sinθ, cosθ, 0).
#       +V(로컬 북)가 진북에서 동으로 11.7° 기울려면
#       −sinθ = +sin11.7° → θ = −11.7°.
AXIS_DEG = -11.7

# 경복궁과 겹치지 않게 띄운 블렌더 원점. 오버데어 배치는 나중에 정한다.
SITE_ORIGIN = (600.0, 0.0, 0.0)

# (U, V, yaw°) — OSM 중심점 실측
#
# ※ 준명당의 U 만 실측값에서 옮겨 놓았다.
#
#    **석어당은 원래 좌표(22.2)로 되돌렸다.** 예전에 +3.4 m 옮겼던 이유는
#    check_roof_clearance 가 U 축만 보는 1차원 검사였기 때문이다. 석어당은
#    즉조당보다 V 로 15 m 남쪽이라 U 가 겹쳐도 지붕이 부딪히지 않는다.
#    2차원 검사로 고치니 어느 이웃과도 간섭이 없다 — 이동이 불필요했다.
#
#    준명당 −18.5 → −19.8 (1.3 m 서쪽) 은 **유지한다.** 준명당(V 57.0)과
#    즉조당(V 56.5)은 나란히 붙어 있어 두 축이 모두 겹치고, OSM 간격에서는
#    실제로 0.9 m 간섭한다. 다만 즉조당 폭(20.10)이 아직 추정이므로,
#    즉조당 실측이 오면 이 이동부터 다시 볼 것.
UV = {
    '중화전': (0.0,     0.0,   0.0),
    '중화문': (0.0,   -67.0,   0.0),
    '즉조당': (2.4,    56.5,   0.0),
    '준명당': (-19.8,  57.0,   0.0),
    '석어당': (22.2,   41.5,   0.0),      # OSM 실측 그대로
    # 대한문만 동향이다.
    # 유도: 저작 프레임의 정면 법선은 −Y. R_z(θ)·(0,−1,0) = (sinθ, −cosθ, 0).
    #       이게 +U = (1,0,0) 이려면 sinθ=1, cosθ=0 → θ = +90°.
    '대한문': (165.9, -56.1,  90.0),
}


def site_matrix(u, v, yaw_deg=0.0, z=0.0):
    """궁 축 좌표 (u, v) 와 건물 자체 회전을 하나의 월드 행렬로 합친다."""
    from mathutils import Matrix
    R = Matrix.Rotation(math.radians(AXIS_DEG), 4, 'Z')
    L = (Matrix.Translation((u, v, z)) @
         Matrix.Rotation(math.radians(yaw_deg), 4, 'Z'))
    return Matrix.Translation(SITE_ORIGIN) @ R @ L


def place(name, objs):
    """UV 표의 항목 이름으로 컬렉션을 제자리에 앉힌다."""
    import hanok
    u, v, yaw = UV[name]
    return hanok.place_objects(objs, matrix=site_matrix(u, v, yaw))


def roof_extent(name):
    """건물의 지붕 외곽 반치수를 (U, V) 축으로 돌려준다.

    yaw 90° 인 건물(대한문)은 폭·깊이가 뒤바뀐다.
    """
    T = {'준명당': (JMD, 'eave_out'), '즉조당': (JJD, 'eave_out'),
         '석어당': (SED, 'eave_out_low'), '대한문': (DHM, 'eave_out')}
    if name not in T:
        return None
    d, ek = T[name]
    eo = d[ek]
    hu = sum(d['bays_x']) / 2.0 + eo
    hv = sum(d['bays_y']) / 2.0 + eo
    yaw = UV[name][2] % 180.0
    if abs(yaw - 90.0) < 1e-6:
        hu, hv = hv, hu
    return hu, hv


def check_roof_clearance(min_gap=0.3):
    """이웃 건물의 **지붕**이 겹치지 않는지 (U, V) 평면에서 검사한다.

    **U 축만 보면 안 된다.** 예전 판본이 그랬는데, 즉조당(V=56.5)과
    석어당(V=41.5)은 V 로 15 m 떨어진 대각선 이웃이라 U 가 겹쳐도
    지붕이 부딪히지 않는다. 그 검사 때문에 석어당을 3.4 m 옮겼었다.

    두 축 모두 겹칠 때만 실제 간섭이다. 반환은 [(a, b, 겹침U, 겹침V), ...]
    로, 비어 있으면 정상.
    """
    names = [n for n in ('준명당', '즉조당', '석어당', '대한문')
             if roof_extent(n)]
    bad = []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            au, av = roof_extent(a)
            bu, bv = roof_extent(b)
            du = abs(UV[b][0] - UV[a][0]) - (au + bu) - min_gap
            dv = abs(UV[b][1] - UV[a][1]) - (av + bv) - min_gap
            if du < 0 and dv < 0:           # 두 축 모두 겹쳐야 간섭이다
                bad.append((a, b, round(-du, 3), round(-dv, 3)))
    return bad


