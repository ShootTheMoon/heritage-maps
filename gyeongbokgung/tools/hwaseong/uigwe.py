# ---------------------------------------------------------------- 척(尺)
#
# 의궤는 척으로만 적는다. 미터 환산값이 필요하다.
# 서북공심돈 총높이를 2차 자료가 "40자(12.32 m)" 로 병기했다:
#     12.32 / 40 = 0.308 m
# 법정 척 303.03 mm 가 아니라 **영조척 308 mm** 다. 덕수궁 석어당에서
# 역산한 307 mm 와 사실상 같다(deoksugung/measured.py JA_MM).
#
# 교차검증: 서옹성 바깥둘레 110척을 반원으로 보면 반지름 = 110/π = 35.0척.
# 의궤가 따로 적은 "문 중심에서 36척" 과 1척 차이로 맞는다. 척값이 맞다는 뜻.
JA_M = (0.308, 'W1 서북공심돈 40자 = 12.32 m 에서 역산. 서옹성 둘레/반지름으로 교차검증',
        'measured')


def ja(cheok, chon=0.0):
    """자·촌 → 미터. 1촌 = 1/10척."""
    return (cheok + chon / 10.0) * JA_M[0]


