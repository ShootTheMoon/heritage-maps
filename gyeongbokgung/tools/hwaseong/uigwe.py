def val(d, k):
    """(값, 출처, 신뢰도) 에서 값만."""
    return d[k][0]


def report(name, d):
    """신뢰도 분포. derived 가 얼마나 남았는지 눈에 보이게."""
    from collections import Counter
    c = Counter(v[2] for v in d.values())
    return "%s: %s" % (name, ", ".join("%s %d" % (k, c[k])
                                       for k in ('measured', 'counted', 'derived')
                                       if c.get(k)))
